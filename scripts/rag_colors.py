"""Write the colour measure of every index that asks for one.

A measure asks for a colour with one annotation in its TMDL:

    annotation RagColor = UpIsGood     -- a rise is good (sales, distribution)
    annotation RagColor = UpIsBad      -- a rise is bad (returns, corrected invoices)

For each, this script writes its colour measure into Measure.tmdl: hidden, in
Formatting\\RAG Color, returning RagColor( [index], centre ) - or, for UpIsBad,
RagColor( -1 * [index], -centre ), so a fall is good. The centre is 1 when the
index, or the measure it repeats, is an IndexRatio, otherwise 0: the same centre
its IndexFormat arrow uses.

An existing colour measure of the index keeps its name and lineageTag; a new one is
named "<index> Color". A colour measure whose index no longer asks for a colour is
removed. Colour measures with their own rule (a score through RagColor) are not
touched: they are not one-line RagColor calls on a single measure.

    python scripts/rag_colors.py           rewrite Measure.tmdl
    python scripts/rag_colors.py --check   report what would change; exit 1 if anything
"""

import io
import os
import re
import sys
import uuid

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(REPO, "Purchasing.SemanticModel", "definition", "tables", "Measure.tmdl")
FOLDER = "Formatting\\RAG Color"
HEAD = re.compile(r"^\tmeasure ('(?:[^']|'')*'|[^\s=]+)\s*=", re.M)
# a colour measure this script owns: one RagColor call on one measure
SIMPLE = re.compile(r"^\s*(?:--[^\n]*\n\s*)*RagColor\s*\(\s*(?:-1\s*\*\s*\[(?P<a>[^\]]+)\]\s*,\s*-?[01]"
                    r"|\[(?P<b>[^\]]+)\]\s*,\s*[01]|[01]\s*,\s*\[(?P<c>[^\]]+)\])\s*\)\s*$")


def quote(name):
    return "'" + name.replace("'", "''") + "'" if re.search(r"[^A-Za-z0-9_]", name) else name


def split(text):
    """Measure.tmdl as [preamble, block, block, ...]; a block starts at its /// description."""
    starts = []
    for m in HEAD.finditer(text):
        s = m.start()
        while True:  # pull the description lines above the measure into its block
            p = text.rfind("\n", 0, s - 1)
            if text[p + 1:s].startswith("\t///"):
                s = p + 1
            else:
                break
        starts.append(s)
    return [text[:starts[0]]] + [text[a:b] for a, b in zip(starts, starts[1:] + [len(text)])]


def parse(block):
    m = HEAD.search(block)
    name = m.group(1).strip("'").replace("''", "'")
    rest = block[m.end():]
    expr = re.split(r"\n\t\t(?!\t)", rest, maxsplit=1)[0]
    ann = re.search(r"\n\t\tannotation RagColor = (UpIsGood|UpIsBad)", block)
    tag = re.search(r"\n\t\tlineageTag: (\S+)", block)
    simple = SIMPLE.match(expr.strip("\n"))
    target = next((g for g in (simple.groupdict().values() if simple else []) if g), None)
    return dict(name=name, expr=expr, direction=ann.group(1) if ann else None,
                tag=tag.group(1) if tag else None, target=target)


def centre(name, measures, seen=()):
    """1 for an IndexRatio, followed through measures that only repeat another one."""
    e = measures[name]["expr"]
    if "IndexRatio" in e:
        return 1
    alias = re.fullmatch(r"\s*\[([^\]]+)\]\s*", e)
    if alias and alias.group(1) in measures and alias.group(1) not in seen:
        return centre(alias.group(1), measures, seen + (name,))
    return 0


def colour_block(name, target, direction, c, tag):
    rises = "rises" if direction == "UpIsGood" else "falls"
    call = f"RagColor( [{target}], {c} )" if direction == "UpIsGood" else f"RagColor( -1 * [{target}], {-c} )"
    return (f"\t/// Theme colour name for [{target}]: good when it {rises}, neutral at {c}, blank when it is blank. "
            f"Generated by scripts/rag_colors.py from the RagColor annotation on [{target}]; edit the annotation, not this measure.\n"
            f"\tmeasure {quote(name)} = {call}\n"
            f"\t\tisHidden\n"
            f"\t\tdisplayFolder: {FOLDER}\n"
            f"\t\tlineageTag: {tag}\n"
            f"\n"
            f"\t\tannotation PBI_FormatHint = {{\"isText\":true}}\n"
            f"\n")


def build(text):
    parts = split(text)
    blocks = [parse(b) for b in parts[1:]]
    measures = {b["name"]: b for b in blocks}
    owned = {b["target"]: b for b in blocks if b["target"]}       # index -> its existing colour measure
    wanted = {b["name"]: b["direction"] for b in blocks if b["direction"]}
    out, changes = [parts[0]], []
    for raw, b in zip(parts[1:], blocks):
        if b["target"] is not None:                               # a colour measure this script owns
            if b["target"] not in wanted:
                changes.append(f"remove {b['name']} (its index asks for no colour)")
                continue
            new = colour_block(b["name"], b["target"], wanted[b["target"]], centre(b["target"], measures), b["tag"])
            if new.rstrip() != raw.rstrip():
                changes.append(f"rewrite {b['name']}")
            out.append(new if raw.endswith("\n\n") else new[:-1])
        else:
            out.append(raw)
    tail = []
    for target, direction in wanted.items():
        if target not in measures:
            changes.append(f"annotation on a missing measure: {target}")
        elif target not in owned:
            name = f"{target} Color"
            tail.append(colour_block(name, target, direction, centre(target, measures), str(uuid.uuid4())))
            changes.append(f"add {name}")
    text = "".join(out)
    if tail:
        text = text.rstrip("\n") + "\n\n" + "".join(tail)
    return text, changes


def main():
    with io.open(PATH, encoding="utf-8", newline="") as f:
        raw = f.read()
    nl = "\r\n" if "\r\n" in raw else "\n"
    text, changes = build(raw.replace("\r\n", "\n"))
    for c in changes:
        print(c)
    print(f"{len(changes)} change(s)")
    if "--check" in sys.argv:
        sys.exit(1 if changes else 0)
    if changes:
        with io.open(PATH, "w", encoding="utf-8", newline="") as f:
            f.write(text.replace("\n", nl))


if __name__ == "__main__":
    main()
